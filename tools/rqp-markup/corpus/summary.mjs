/** @param {number} n @param {number} d */
export const pct = (n, d) => (d === 0 ? "–" : `${((100 * n) / d).toFixed(1)} %`);

/** Pages that have class c (total) and pages where c is the only class (alone). */
export function classStats(pages, key = "classes") {
  const stats = new Map();
  for (const p of pages) {
    const cls = Object.keys(p[key] ?? {});
    for (const c of cls) {
      const s = stats.get(c) ?? { total: 0, alone: 0, pages: [], alonePages: [] };
      s.total++;
      s.pages.push(p);
      if (cls.length === 1) {
        s.alone++;
        s.alonePages.push(p);
      }
      stats.set(c, s);
    }
  }
  return stats;
}

/** Group classes by a key function (for example the rule id). */
export function regroup(pages, fn, key = "classes") {
  return pages.map((p) => {
    const out = {};
    for (const c of Object.keys(p[key] ?? {})) out[fn(c)] = 1;
    return { ...p, [key]: out };
  });
}

/**
 * Greedy order of rule removals: at each step remove the rule that makes the most rejected
 * pages pass. Returns the steps with the cumulative number of valid pages.
 */
export function greedy(pages, steps, key = "classes") {
  const removed = new Set();
  const out = [];
  const validNow = () => pages.filter((p) => Object.keys(p[key] ?? {}).every((c) => removed.has(c))).length;
  for (let s = 0; s < steps; s++) {
    let best = null;
    let bestN = validNow();
    const all = new Set(pages.flatMap((p) => Object.keys(p[key] ?? {})));
    for (const c of [...all].sort()) {
      if (removed.has(c)) continue;
      removed.add(c);
      const n = validNow();
      removed.delete(c);
      if (n > bestN) {
        best = c;
        bestN = n;
      }
    }
    if (best === null) break;
    removed.add(best);
    out.push({ rule: best, valid: bestN });
  }
  return out;
}

const examples = (list, n = 2) => list.slice(0, n).map((p) => p.url);

function table(head, rows) {
  const lines = [`| ${head.join(" | ")} |`, `|${head.map((_, i) => (i === 0 ? "---" : "--:")).join("|")}|`];
  for (const r of rows) lines.push(`| ${r.join(" | ")} |`);
  return lines.join("\n");
}

function detailCounts(pages, cls, field = "details", re = null) {
  const m = new Map();
  for (const p of pages) {
    const d = p[field]?.[cls];
    if (!d) continue;
    const seen = new Set();
    for (const k of Object.keys(d)) {
      const key = re ? (re.exec(k)?.[1] ?? k) : k;
      if (seen.has(key)) continue;
      seen.add(key);
      m.set(key, (m.get(key) ?? 0) + 1);
    }
  }
  return [...m].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1));
}

